"""XHand G1 used for the newer Weave (G1-Xhand-OMOMO) HOI clips.

``robot_assets/unitree_g1/g1_29dof_rev_1_0_xhand.xml`` is a standalone MuJoCo model,
committed ready to load. :func:`regenerate_xml` produces it from the vendored URDF
next to it and applies the edits the URDF needs to be usable here:

* a free joint on ``pelvis`` (the URDF has no floating base);
* geom names, so mjlab's ``CollisionCfg`` regexes and ``foot_geom_expr`` can
  select feet and hands — the URDF importer leaves every geom unnamed;
* mesh refs split across the shared ``meshes`` directory: G1 body meshes flatten
  into it (byte-identical to the ones already there for the other G1 assets, so
  nothing is duplicated), while the XHand hands and wrist adapter go to
  ``meshes/g1_xhand`` so they stay distinguishable from G1 and Inspire parts.

Visual meshes are kept (``discardvisual="false"``) because the viewer draws them.
Collision geoms are the URDF's (mesh for the body, spheres for the feet, cylinders
for the shoulders), with ``contype=0`` / ``conaffinity=1`` so the robot does not
self-collide but still touches terrain and the free object — the same policy
``g1_hoi_learning`` sets with ``enabled_self_collisions=False``.

Finger hinges use XHand's own PD gains; the 29 body joints reuse the mjlab G1
actuator constants.
"""

from __future__ import annotations

import collections
from pathlib import Path

import mujoco
from mjlab.actuator import BuiltinPositionActuatorCfg
from mjlab.asset_zoo.robots.unitree_g1.g1_constants import (
    G1_ACTUATOR_4010,
    G1_ACTUATOR_5020,
    G1_ACTUATOR_7520_14,
    G1_ACTUATOR_7520_22,
    G1_ACTUATOR_ANKLE,
    G1_ACTUATOR_WAIST,
)
from mjlab.entity import EntityArticulationInfoCfg, EntityCfg
from mjlab.utils.spec_config import CollisionCfg
from mjlab.utils.string import resolve_expr

_REPO_ROOT = Path(__file__).resolve().parents[3]
# The vendored URDF is the source of truth; XML_PATH is generated from it.
URDF_PATH = _REPO_ROOT / "robot_assets" / "unitree_g1" / "g1_29dof_rev_1_0_xhand.urdf"
# Committed, ready to load. Generated by ``python -m supermimic.robots.g1_xhand``.
XML_PATH = _REPO_ROOT / "robot_assets" / "unitree_g1" / "g1_29dof_rev_1_0_xhand.xml"
# Shared mesh directory. The G1 body meshes sit here; the XHand-specific ones
# (hands + adapter) in its ``g1_xhand`` subfolder.
MESH_DIR = _REPO_ROOT / "robot_assets" / "unitree_g1" / "meshes"
XHAND_MESH_DIR = MESH_DIR / "g1_xhand"

FREE_JOINT = "floating_base_joint"
FEET = ("left_ankle_roll_link", "right_ankle_roll_link")

# ``_mujoco_`` block injected before ``</robot>``. ``discardvisual="false"`` keeps
# the URDF's <visual> meshes, which the importer drops by default.
_MUJOCO_BLOCK = '<mujoco>\n    <compiler discardvisual="false"/>\n  </mujoco>\n'

# XHand finger drive (g1_hoi_learning.robots.g1_xhand).
_FINGER_STIFFNESS = 3.0
_FINGER_DAMPING = 0.08
_FINGER_ARMATURE = 1e-4
_FINGER_FRICTIONLOSS = 0.005
# Two effort classes: proximal/bend joints are the stronger 1.1 N·m motors.
_FINGER_STRONG = (
    ".*_hand_thumb_bend_joint",
    ".*_hand_thumb_rota_joint1",
    ".*_hand_index_joint1",
    ".*_hand_mid_joint1",
    ".*_hand_ring_joint1",
    ".*_hand_pinky_joint1",
)
_FINGER_WEAK = (
    ".*_hand_thumb_rota_joint2",
    ".*_hand_index_bend_joint",
    ".*_hand_index_joint2",
    ".*_hand_mid_joint2",
    ".*_hand_ring_joint2",
    ".*_hand_pinky_joint2",
)

ARTICULATION = EntityArticulationInfoCfg(
    actuators=(
        G1_ACTUATOR_5020,
        G1_ACTUATOR_7520_14,
        G1_ACTUATOR_7520_22,
        G1_ACTUATOR_4010,
        G1_ACTUATOR_WAIST,
        G1_ACTUATOR_ANKLE,
        BuiltinPositionActuatorCfg(
            target_names_expr=_FINGER_STRONG,
            stiffness=_FINGER_STIFFNESS,
            damping=_FINGER_DAMPING,
            effort_limit=1.1,
            armature=_FINGER_ARMATURE,
            frictionloss=_FINGER_FRICTIONLOSS,
        ),
        BuiltinPositionActuatorCfg(
            target_names_expr=_FINGER_WEAK,
            stiffness=_FINGER_STIFFNESS,
            damping=_FINGER_DAMPING,
            effort_limit=0.4,
            armature=_FINGER_ARMATURE,
            frictionloss=_FINGER_FRICTIONLOSS,
        ),
    ),
    soft_joint_pos_limit_factor=0.9,
)

# XHand drives its fingers at the commanded angle (scale 1 rad/action), matching
# g1_hoi_learning's ``G1_XHAND_ACTION_SCALE``. Body joints follow mjlab's
# ``0.25 * effort / stiffness`` convention.
ACTION_SCALE: dict[str, float] = {".*_hand_.*": 1.0}
for _actuator in ARTICULATION.actuators:
    assert isinstance(_actuator, BuiltinPositionActuatorCfg)
    if any(_pattern == ".*_hand_.*" for _pattern in _actuator.target_names_expr):
        continue
    assert _actuator.effort_limit is not None
    for _pattern in _actuator.target_names_expr:
        ACTION_SCALE[_pattern] = 0.25 * _actuator.effort_limit / _actuator.stiffness


def xhand_spec() -> mujoco.MjSpec:
    """XHand MJCF: floating base, named geoms, visual meshes kept.

    ``robot_assets/unitree_g1/g1_29dof_rev_1_0_xhand.xml`` is committed ready to
    load: generated once from the vendored URDF, with the free joint, geom names
    and collision flags already written. Re-generating it needs the URDF; loading
    does not.
    """
    if not XML_PATH.is_file():
        raise FileNotFoundError(f"XHand MJCF not found at {XML_PATH}.")
    return mujoco.MjSpec.from_file(str(XML_PATH))


def _name_geoms(spec: mujoco.MjSpec) -> None:
    """Give every geom a name so regex selection and the viewer work.

    Only used by :func:`regenerate_xml`; the committed XML already has these names.
    Collision geoms become ``<body>_collision_<i>``, except on the ankle-roll links
    where they become ``<side>_foot_collision_<i>`` to match ``foot_geom_expr``.
    Visual meshes become ``<body>_visual_<i>``.
    """
    counts: dict[tuple[str, bool], int] = collections.defaultdict(int)
    for geom in spec.geoms:
        is_collision = bool(int(geom.contype) or int(geom.conaffinity))
        body = geom.parent.name
        index = counts[(body, is_collision)]
        counts[(body, is_collision)] += 1
        if is_collision:
            side = "left" if body.startswith("left_") else "right"
            if body in FEET:
                geom.name = f"{side}_foot_collision_{index + 1}"
            else:
                geom.name = f"{body}_collision_{index + 1}"
            geom.group = 3
        else:
            geom.name = f"{body}_visual_{index + 1}"
            geom.group = 2


def hinge_joint_names(model: mujoco.MjModel) -> tuple[str, ...]:
    names: list[str] = []
    for joint_id in range(model.njnt):
        if int(model.jnt_type[joint_id]) == int(mujoco.mjtJoint.mjJNT_FREE):
            continue
        name = mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_JOINT, joint_id)
        if name:
            names.append(name)
    return tuple(names)


def compile_g1_xhand() -> tuple[mujoco.MjModel, tuple[str, ...]]:
    model = xhand_spec().compile()
    return model, hinge_joint_names(model)


def robot_cfg() -> EntityCfg:
    return EntityCfg(
        init_state=EntityCfg.InitialStateCfg(pos=(0.0, 0.0, 0.76), joint_pos={".*": 0.0}),
        spec_fn=xhand_spec,
        articulation=ARTICULATION,
        collisions=(
            CollisionCfg(
                geom_names_expr=(".*_collision.*",),
                # contype 0 / conaffinity 1: no robot self-collision, but contacts
                # with terrain and the object (both contype 1 / conaffinity 1).
                contype=0,
                conaffinity=1,
                solref=(0.01, 1),
                condim={
                    ".*_foot_collision_[0-9]+$": 6,
                    ".*_hand_.*_collision.*": 6,
                    ".*_collision.*": 1,
                },
                priority={
                    ".*_foot_collision_[0-9]+$": 1,
                    ".*_hand_.*_collision.*": 1,
                    ".*": 0,
                },
                friction={
                    ".*_foot_collision_[0-9]+$": (1.0, 5e-3, 5e-4),
                    ".*_hand_.*_collision.*": (1.0, 5e-3, 5e-4),
                },
            ),
        ),
    )


def action_scale(joint_names: tuple[str, ...]) -> list[float]:
    scale = list(resolve_expr(ACTION_SCALE, joint_names))
    missing = [name for name, value in zip(joint_names, scale) if value is None]
    if missing:
        raise KeyError(f"No XHand action scale for joints {missing}")
    return [float(value) for value in scale]


def regenerate_xml() -> Path:
    """Rebuild ``XML_PATH`` from the vendored URDF.

    Applies the three edits once and writes a standalone MJCF whose ``meshdir`` is
    the relative ``meshes/`` next to it, so loading needs neither the URDF nor any
    path rewriting. Run after replacing the URDF::

        python -m supermimic.robots.g1_xhand
    """
    import re

    if not URDF_PATH.is_file():
        raise FileNotFoundError(f"XHand URDF not found at {URDF_PATH}.")
    text = URDF_PATH.read_text()

    def _mesh_ref(match: re.Match[str]) -> str:
        # G1 body meshes share the mesh directory with the other G1 assets; the
        # hand and adapter meshes live in its ``g1_xhand`` subfolder.
        group, name = match.group(1), match.group(2)
        return f'filename="{name}"' if group == "g1" else f'filename="g1_xhand/{name}"'

    text = re.sub(r'filename="meshes/([^/]+)/([^"]+)"', _mesh_ref, text)
    if "</robot>" not in text:
        raise ValueError(f"{URDF_PATH} has no closing </robot> tag.")
    # ``discardvisual="false"`` keeps the <visual> meshes the importer drops.
    text = text.replace("</robot>", f"{_MUJOCO_BLOCK}</robot>")
    spec = mujoco.MjSpec.from_string(text)
    # to_xml resolves mesh files, so it needs an absolute directory here.
    spec.compiler.meshdir = str(MESH_DIR.resolve())
    pelvis = spec.body("pelvis")
    if not list(pelvis.joints):
        pelvis.add_freejoint().name = FREE_JOINT
    _name_geoms(spec)
    for geom in spec.geoms:
        if not geom.name or "_collision_" not in geom.name:
            continue
        geom.contype = 0
        geom.conaffinity = 1
        geom.solref = [0.01, 1.0]
        grip = "foot_collision" in geom.name or "_hand_" in geom.name
        geom.condim = 6 if grip else 1
        geom.priority = 1 if grip else 0
        if grip:
            geom.friction = [1.0, 5e-3, 5e-4]
    spec.modelname = "g1_29dof_rev_1_0_xhand"
    xml = spec.to_xml().replace(str(MESH_DIR.resolve()), "meshes")
    XML_PATH.parent.mkdir(parents=True, exist_ok=True)
    XML_PATH.write_text(xml)
    print(f"wrote {XML_PATH} ({XML_PATH.stat().st_size} bytes)", flush=True)
    return XML_PATH


if __name__ == "__main__":
    regenerate_xml()
